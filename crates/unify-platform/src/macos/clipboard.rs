use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;
use std::thread::JoinHandle;
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use objc2_foundation::NSString;

use crate::{ChangeSink, ClipboardText, PlatformError, StopHandle};

const POLL_INTERVAL: Duration = Duration::from_millis(250);
const CONCEALED_TYPES: &[&str] = &["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

fn change_count() -> isize {
    autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.changeCount()
    })
}

pub fn read_text() -> Result<Option<ClipboardText>, PlatformError> {
    Ok(autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        let concealed = pasteboard
            .types()
            .map(|types| types.iter().any(|kind| CONCEALED_TYPES.iter().any(|concealed| kind.to_string() == *concealed)))
            .unwrap_or(false);
        let text = unsafe { pasteboard.stringForType(NSPasteboardTypeString) }?;
        Some(ClipboardText { text: text.to_string(), concealed })
    }))
}

pub fn write_text(text: &str) -> Result<(), PlatformError> {
    autoreleasepool(|_| {
        let pasteboard = NSPasteboard::generalPasteboard();
        pasteboard.clearContents();
        let value = NSString::from_str(text);
        if unsafe { pasteboard.setString_forType(&value, NSPasteboardTypeString) } {
            Ok(())
        } else {
            Err(PlatformError::Os(String::from("NSPasteboard rejected the text")))
        }
    })
}

pub struct ClipboardPoller {
    stopping: Arc<AtomicBool>,
    join: Option<JoinHandle<()>>,
}

impl ClipboardPoller {
    pub fn start(sink: ChangeSink) -> Result<Self, PlatformError> {
        let stopping = Arc::new(AtomicBool::new(false));
        let flag = stopping.clone();
        let join = std::thread::Builder::new()
            .name("unify-pasteboard".into())
            .spawn(move || {
                let mut last = change_count();
                while !flag.load(Ordering::Relaxed) {
                    std::thread::sleep(POLL_INTERVAL);
                    let current = change_count();
                    if current != last {
                        last = current;
                        sink();
                    }
                }
            })
            .map_err(|err| PlatformError::Os(err.to_string()))?;
        Ok(Self { stopping, join: Some(join) })
    }
}

impl StopHandle for ClipboardPoller {
    fn stop(mut self: Box<Self>) {
        self.stopping.store(true, Ordering::Relaxed);
        if let Some(join) = self.join.take() {
            let _ = join.join();
        }
    }
}
