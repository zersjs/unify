const MAC_USAGE_ALIASES: &[(u16, u16)] = &[(0x46, 0x69), (0x47, 0x6B), (0x48, 0x71), (usage::NON_US_HASH, 0x2A)];

const MAC_ISO_SECTION: u16 = 0x0A;
const MAC_ANSI_GRAVE: u16 = 0x32;

fn lookup_forward(table: &[(u16, u16)], usage: u16) -> Option<u16> {
    table.iter().find(|(hid, _)| *hid == usage).map(|(_, native)| *native)
}

fn lookup_reverse(table: &[(u16, u16)], native: u16) -> Option<u16> {
    table.iter().find(|(_, code)| *code == native).map(|(hid, _)| *hid)
}

pub fn windows_scancode_to_usage(scancode: u16) -> Option<u16> {
    lookup_reverse(WINDOWS_SCANCODES, scancode).or_else(|| lookup_forward(WINDOWS_SCANCODE_ALIASES, scancode))
}

pub fn usage_to_windows_scancode(usage: u16) -> Option<u16> {
    lookup_forward(WINDOWS_SCANCODES, usage).or_else(|| lookup_forward(WINDOWS_USAGE_ALIASES, usage))
}

pub fn mac_keycode_to_usage(keycode: u16, iso_keyboard: bool) -> Option<u16> {
    if iso_keyboard {
        match keycode {
            MAC_ISO_SECTION => return Some(usage::GRAVE),
            MAC_ANSI_GRAVE => return Some(usage::NON_US_BACKSLASH),
            _ => {}
        }
    }
    lookup_reverse(MAC_KEYCODES, keycode)
}

pub fn usage_to_mac_keycode(usage: u16, iso_keyboard: bool) -> Option<u16> {
    if iso_keyboard && usage == usage::GRAVE {
        return Some(MAC_ISO_SECTION);
    }
    if iso_keyboard && usage == usage::NON_US_BACKSLASH {
        return Some(MAC_ANSI_GRAVE);
    }
    lookup_forward(MAC_KEYCODES, usage).or_else(|| lookup_forward(MAC_USAGE_ALIASES, usage))
}

pub fn is_modifier(usage: u16) -> bool {
    (usage::LEFT_CTRL..=usage::RIGHT_GUI).contains(&usage)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn windows_table_is_bijective() {
        for (hid, scan) in WINDOWS_SCANCODES {
            assert_eq!(windows_scancode_to_usage(*scan), Some(*hid), "scan {scan:#x}");
            assert_eq!(usage_to_windows_scancode(*hid), Some(*scan), "hid {hid:#x}");
        }
        let mut hids: Vec<u16> = WINDOWS_SCANCODES.iter().map(|(h, _)| *h).collect();
        hids.sort_unstable();
        hids.dedup();
        assert_eq!(hids.len(), WINDOWS_SCANCODES.len());
        let mut scans: Vec<u16> = WINDOWS_SCANCODES.iter().map(|(_, s)| *s).collect();
        scans.sort_unstable();
        scans.dedup();
        assert_eq!(scans.len(), WINDOWS_SCANCODES.len());
    }

    #[test]
    fn mac_table_is_bijective_for_ansi() {
        for (hid, code) in MAC_KEYCODES {
            assert_eq!(mac_keycode_to_usage(*code, false), Some(*hid), "code {code:#x}");
            assert_eq!(usage_to_mac_keycode(*hid, false), Some(*code), "hid {hid:#x}");
        }
        let mut codes: Vec<u16> = MAC_KEYCODES.iter().map(|(_, c)| *c).collect();
        codes.sort_unstable();
        codes.dedup();
        assert_eq!(codes.len(), MAC_KEYCODES.len());
    }

    #[test]
    fn mac_iso_keyboard_swaps_section_and_grave() {
        assert_eq!(mac_keycode_to_usage(MAC_ISO_SECTION, true), Some(usage::GRAVE));
        assert_eq!(mac_keycode_to_usage(MAC_ANSI_GRAVE, true), Some(usage::NON_US_BACKSLASH));
        assert_eq!(usage_to_mac_keycode(usage::GRAVE, true), Some(MAC_ISO_SECTION));
        assert_eq!(usage_to_mac_keycode(usage::NON_US_BACKSLASH, true), Some(MAC_ANSI_GRAVE));
        assert_eq!(mac_keycode_to_usage(MAC_ISO_SECTION, false), Some(usage::NON_US_BACKSLASH));
        assert_eq!(mac_keycode_to_usage(MAC_ANSI_GRAVE, false), Some(usage::GRAVE));
    }

    #[test]
    fn iso_keyboard_roundtrips_every_key() {
        for (hid, _) in MAC_KEYCODES {
            let code = usage_to_mac_keycode(*hid, true).expect("mapped");
            assert_eq!(mac_keycode_to_usage(code, true), Some(*hid));
        }
    }

    #[test]
    fn turkish_q_letter_positions_cross_platform() {
        let turkish_specific = [0x2F, 0x30, 0x33, 0x34, 0x36, 0x37, 0x31, 0x64];
        for hid in turkish_specific {
            let win = usage_to_windows_scancode(hid).expect("windows");
            let mac = usage_to_mac_keycode(hid, true).expect("mac");
            assert_eq!(windows_scancode_to_usage(win), Some(hid));
            assert_eq!(mac_keycode_to_usage(mac, true), Some(hid));
        }
    }

    #[test]
    fn aliases_resolve() {
        assert_eq!(windows_scancode_to_usage(0xE036), Some(usage::RIGHT_SHIFT));
        assert_eq!(windows_scancode_to_usage(0x54), Some(0x46));
        assert_eq!(usage_to_windows_scancode(usage::NON_US_HASH), Some(0x2B));
        assert_eq!(usage_to_mac_keycode(0x46, false), Some(0x69));
        assert_eq!(usage_to_mac_keycode(usage::NON_US_HASH, false), Some(0x2A));
        assert_eq!(windows_scancode_to_usage(0x7FFF), None);
        assert_eq!(mac_keycode_to_usage(0x3F, false), None);
    }

    #[test]
    fn modifier_range() {
        assert!(is_modifier(usage::LEFT_CTRL));
        assert!(is_modifier(usage::RIGHT_GUI));
        assert!(!is_modifier(usage::SPACE));
    }
}
